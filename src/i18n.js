export function normalizeLanguage(language) {
  return Object.hasOwn(languages, language) ? language : defaultLanguage;
}

export function translate(language, key) {
  const safeLanguage = normalizeLanguage(language);
  return translations[safeLanguage][key] ?? translations[defaultLanguage][key] ?? key;
}

export function localizeSeedHabit(habit, language) {
  const copy = localizedSeedHabits[normalizeLanguage(language)][habit.id];
  return copy ? { ...habit, ...copy } : habit;
}

export function localizeRoutinePack(pack, language) {
  const copy = localizedRoutinePacks[normalizeLanguage(language)][pack.id];
  return copy ? { ...pack, ...copy } : pack;
}

export function localizeImportedRoutineHabit(habit, language) {
  if (!habit.sourceRoutineId || typeof habit.sourceRoutineIndex !== 'number') return habit;

  const pack = localizedRoutinePacks[normalizeLanguage(language)][habit.sourceRoutineId];
  const title = pack?.habits?.[habit.sourceRoutineIndex];
  return title ? { ...habit, title, category: pack.tag } : habit;
}
